import 'package:flutter/material.dart';

import '../../core/constants/app_colors.dart';
import '../../core/constants/app_dimensions.dart';
import '../../core/services/analytics_service.dart';
import 'analytics_dashboard_widgets.dart';
import 'analytics_result_view_model.dart';

// Estado real del dashboard de VV2: la pantalla está implementada y lee
// analytics_results/planning_abandonment_FLUTTER, pero ese documento solo
// existe si alguien ejecuta analytics/planning_abandonment.js
// (actualizar_dashboards.cmd) con la llave de la cuenta de servicio. No se
// ejecuta solo ni desde la app.
/// Dashboard for the VV2 business question:
/// "At which step do users most frequently abandon the meeting planning
/// process?"
///
/// Shows `analytics_results/planning_abandonment_FLUTTER`, produced by
/// `analytics/planning_abandonment.js` from the PLANNING_* events written by
/// [AnalyticsService]. No sample data: if the aggregate does not exist yet,
/// an empty state explains how to generate it.
class PlanningAbandonmentPage extends StatefulWidget {
  const PlanningAbandonmentPage({super.key});

  static const String docId = 'planning_abandonment_FLUTTER';

  @override
  State<PlanningAbandonmentPage> createState() => _PlanningAbandonmentPageState();
}

class _PlanningAbandonmentPageState extends State<PlanningAbandonmentPage> {
  late final AnalyticsResultViewModel _viewModel =
      AnalyticsResultViewModel(docId: PlanningAbandonmentPage.docId)..start();

  @override
  void dispose() {
    _viewModel.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return AnalyticsDashboardScaffold(
      title: 'Planning abandonment',
      viewModel: _viewModel,
      emptyMessage:
          'There is no aggregated result yet. It is generated by running '
          'analytics/planning_abandonment.js with the project credentials.',
      builder: (context, data) => _Content(data: data),
    );
  }
}

const _stepLabels = {
  MeetingPlanningStep.details: '1. Details',
  MeetingPlanningStep.vote: '2. Vote',
  MeetingPlanningStep.result: '3. Winning place',
};

const _reasonLabels = {
  PlanningAbandonReason.leftScreen: 'Left the screen',
  PlanningAbandonReason.navigation: 'Went to another section',
  PlanningAbandonReason.appClosed: 'Closed the app',
  PlanningAbandonReason.restarted: 'Started another attempt',
};

class _Content extends StatelessWidget {
  final Map<String, dynamic> data;
  const _Content({required this.data});

  @override
  Widget build(BuildContext context) {
    const i = AnalyticsResultViewModel.intOf;
    // Todos los valores vienen del agregado: sampleCount = intentos terminados
    // (completados + abandonados); los intentos abiertos no entran en las
    // tasas.
    final sample = i(data['sampleCount']);
    final completed = i(data['completedAttempts']);
    final abandoned = i(data['abandonedAttempts']);
    final open = i(data['openAttempts']);
    final byStep = AnalyticsResultViewModel.mapOf(data['byStep']);
    final reasons = AnalyticsResultViewModel.mapOf(data['abandonReasons']);
    final peak = AnalyticsResultViewModel.mapOf(data['peakAbandonStep']);
    final updated = AnalyticsResultViewModel.updatedAtLabel(data);

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const QuestionBanner(
          label: 'Abandonment BQ (Viva Voce 2)',
          question:
              'At which step do users most frequently abandon the meeting planning process?',
        ),
        const SizedBox(height: AppDimensions.paddingM),
        if (sample == 0) ...[
          DashboardMessage(
            icon: Icons.hourglass_empty,
            message: open > 0
                ? 'There are $open attempts in progress, but none has finished yet.'
                : 'The aggregate exists but has no planning attempts yet.',
          ),
        ] else ...[
          // Antes era un GridView con proporción fija (childAspectRatio 2.2):
          // la altura de cada celda no alcanzaba para número + etiqueta y se
          // desbordaba ~11 px. Ahora son dos filas cuya altura se ajusta al
          // contenido.
          StatTileGrid(tiles: [
            StatTile(label: 'Finished attempts', value: '$sample'),
            StatTile(
                label: 'Completion rate',
                value: percent(AnalyticsResultViewModel.doubleOf(data['completionRate']))),
            StatTile(label: 'Completed', value: '$completed'),
            StatTile(label: 'Abandoned', value: '$abandoned'),
          ]),
          const SizedBox(height: AppDimensions.paddingM),
          Text(
            peak.isEmpty
                ? 'No finished attempt was abandoned.'
                : 'Step with the most abandonments: ${_stepLabels[peak['step']] ?? peak['step']} '
                    '(${i(peak['abandoned'])} attempts, '
                    '${percent(AnalyticsResultViewModel.doubleOf(peak['abandonRate']))} of those who reached it).',
            style: const TextStyle(
                fontWeight: FontWeight.w600, color: AppColors.text),
          ),
          const SectionHeader('Abandonments by step'),
          BarList(rows: [
            for (final step in _stepLabels.keys)
              (
                _stepLabels[step]!,
                i(AnalyticsResultViewModel.mapOf(byStep[step])['abandoned']),
                '${i(AnalyticsResultViewModel.mapOf(byStep[step])['abandoned'])}',
              ),
          ]),
          const SectionHeader('Abandonment rate (of those who reached the step)'),
          BarList(
            max: 1,
            rows: [
              for (final step in _stepLabels.keys)
                (
                  '${_stepLabels[step]!} (${i(AnalyticsResultViewModel.mapOf(byStep[step])['reached'])})',
                  AnalyticsResultViewModel.doubleOf(
                      AnalyticsResultViewModel.mapOf(byStep[step])['abandonRate']),
                  percent(AnalyticsResultViewModel.doubleOf(
                      AnalyticsResultViewModel.mapOf(byStep[step])['abandonRate'])),
                ),
            ],
          ),
          if (reasons.isNotEmpty) ...[
            const SectionHeader('How it was abandoned'),
            BarList(rows: [
              for (final entry in reasons.entries)
                (_reasonLabels[entry.key] ?? entry.key, i(entry.value), '${i(entry.value)}'),
            ]),
          ],
        ],
        const SizedBox(height: AppDimensions.paddingL),
        Text(
          [
            if (open > 0) '$open attempts in progress are not included in the rates.',
            if (i(data['ignoredEvents']) > 0)
              '${i(data['ignoredEvents'])} events ignored because of incomplete data.',
            if (updated != null) 'Updated: $updated',
          ].join('\n'),
          style: const TextStyle(fontSize: 12, color: AppColors.textSecondary),
        ),
      ],
    );
  }
}
