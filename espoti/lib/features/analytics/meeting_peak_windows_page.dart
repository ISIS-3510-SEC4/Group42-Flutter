import 'package:flutter/material.dart';

import '../../core/constants/app_colors.dart';
import '../../core/constants/app_dimensions.dart';
import '../../models/transit_mode.dart';
import 'analytics_dashboard_widgets.dart';
import 'analytics_result_view_model.dart';

// Estado real del dashboard de BQ tipo 4: igual que el de abandono, depende de
// ejecutar analytics/meeting_peak_windows.js; sin ese documento muestra el
// estado vacío.
/// Dashboard for the VV3 business question (type 4):
/// "What are the peak days and time windows during which groups organize
/// meetings, broken down by transit mode?"
///
/// Shows `analytics_results/meeting_peak_windows_FLUTTER`, produced by
/// `analytics/meeting_peak_windows.js` from the MEETING_CREATED events
/// (MeetingCreationTracker). No sample data.
class MeetingPeakWindowsPage extends StatefulWidget {
  const MeetingPeakWindowsPage({super.key});

  static const String docId = 'meeting_peak_windows_FLUTTER';

  @override
  State<MeetingPeakWindowsPage> createState() => _MeetingPeakWindowsPageState();
}

class _MeetingPeakWindowsPageState extends State<MeetingPeakWindowsPage> {
  late final AnalyticsResultViewModel _viewModel =
      AnalyticsResultViewModel(docId: MeetingPeakWindowsPage.docId)..start();
  String? _selectedMode;

  @override
  void dispose() {
    _viewModel.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return AnalyticsDashboardScaffold(
      title: 'Meeting peaks',
      viewModel: _viewModel,
      emptyMessage:
          'There is no aggregated result yet. It is generated by running '
          'analytics/meeting_peak_windows.js with the project credentials.',
      builder: (context, data) => _content(data),
    );
  }

  Widget _content(Map<String, dynamic> data) {
    const i = AnalyticsResultViewModel.intOf;
    final sample = i(data['sampleCount']);
    final byMode = AnalyticsResultViewModel.mapOf(data['byTransitMode']);
    final peaks = AnalyticsResultViewModel.mapOf(data['peaks']);
    final modes = byMode.keys.toList()
      ..sort((a, b) => i(AnalyticsResultViewModel.mapOf(byMode[b])['total'])
          .compareTo(i(AnalyticsResultViewModel.mapOf(byMode[a])['total'])));
    final selected =
        modes.contains(_selectedMode) ? _selectedMode! : (modes.isEmpty ? null : modes.first);
    final updated = AnalyticsResultViewModel.updatedAtLabel(data);

    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const QuestionBanner(
          label: 'BQ Type 4 (Viva Voce 3)',
          question:
              'What are the peak days and time windows during which groups organize meetings, by transit mode?',
        ),
        const SizedBox(height: AppDimensions.paddingM),
        if (sample == 0 || selected == null)
          const DashboardMessage(
            icon: Icons.hourglass_empty,
            message: 'The aggregate exists but does not include any meetings yet.',
          )
        else ...[
          Text('$sample meetings analyzed',
              style: const TextStyle(fontWeight: FontWeight.w600, color: AppColors.text)),
          const SectionHeader('Meetings by transit mode'),
          BarList(rows: [
            for (final mode in modes)
              (
                _modeLabel(mode),
                i(AnalyticsResultViewModel.mapOf(byMode[mode])['total']),
                '${i(AnalyticsResultViewModel.mapOf(byMode[mode])['total'])}',
              ),
          ]),
          const SizedBox(height: AppDimensions.paddingM),
          Wrap(
            spacing: AppDimensions.paddingS,
            children: [
              for (final mode in modes)
                ChoiceChip(
                  label: Text(_modeLabel(mode)),
                  selected: mode == selected,
                  onSelected: (_) => setState(() => _selectedMode = mode),
                ),
            ],
          ),
          ..._modeDetail(
            AnalyticsResultViewModel.mapOf(byMode[selected]),
            AnalyticsResultViewModel.mapOf(peaks[selected]),
          ),
        ],
        const SizedBox(height: AppDimensions.paddingL),
        Text(
          [
            'Local time of the device that created the meeting.',
            if (i(data['ignoredEvents']) > 0)
              '${i(data['ignoredEvents'])} events ignored (incomplete or duplicated).',
            if (updated != null) 'Updated: $updated',
          ].join('\n'),
          style: const TextStyle(fontSize: 12, color: AppColors.textSecondary),
        ),
      ],
    );
  }

  List<Widget> _modeDetail(Map<String, dynamic> mode, Map<String, dynamic> peaks) {
    String peakText(String key, String Function(String) label) {
      final peak = AnalyticsResultViewModel.mapOf(peaks[key]);
      final value = peak['key'];
      if (value is! String) return 'No data';
      return '${label(value)} (${AnalyticsResultViewModel.intOf(peak['count'])})';
    }

    return [
      const SectionHeader('Peaks'),
      _PeakRow('Day most meetings are organized', peakText('peakCreatedDay', _dayLabel)),
      _PeakRow('Window most meetings are organized', peakText('peakCreatedWindow', _windowLabel)),
      _PeakRow('Day + window', peakText('peakCreatedDayAndWindow', _dayWindowLabel)),
      _PeakRow('Most scheduled day', peakText('peakScheduledDay', _dayLabel)),
      _PeakRow('Most scheduled window', peakText('peakScheduledWindow', _windowLabel)),
      const SectionHeader('Created by day'),
      _counts(AnalyticsResultViewModel.mapOf(mode['createdByDay']), _days, _dayLabel),
      const SectionHeader('Created by time window'),
      _counts(AnalyticsResultViewModel.mapOf(mode['createdByWindow']), _windows, _windowLabel),
      const SectionHeader('Scheduled by day'),
      _counts(AnalyticsResultViewModel.mapOf(mode['scheduledByDay']), _days, _dayLabel),
      const SectionHeader('Scheduled by time window'),
      _counts(AnalyticsResultViewModel.mapOf(mode['scheduledByWindow']), _windows, _windowLabel),
    ];
  }

  Widget _counts(Map<String, dynamic> counts, List<String> order,
      String Function(String) label) {
    if (counts.isEmpty) {
      return const Text('No data',
          style: TextStyle(fontSize: 12, color: AppColors.textSecondary));
    }
    return BarList(rows: [
      for (final key in order)
        (
          label(key),
          AnalyticsResultViewModel.intOf(counts[key]),
          '${AnalyticsResultViewModel.intOf(counts[key])}',
        ),
    ]);
  }

  static String _modeLabel(String wire) =>
      TransitMode.fromWire(wire)?.label ??
      (wire == 'UNSPECIFIED' ? 'Not specified' : wire);

  static const _days = [
    'MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY',
  ];
  static const _dayNames = {
    'MONDAY': 'Monday', 'TUESDAY': 'Tuesday', 'WEDNESDAY': 'Wednesday',
    'THURSDAY': 'Thursday', 'FRIDAY': 'Friday', 'SATURDAY': 'Saturday',
    'SUNDAY': 'Sunday',
  };
  static const _windows = [
    'EARLY_MORNING', 'MORNING', 'MIDDAY', 'AFTERNOON', 'EVENING', 'NIGHT',
  ];
  // Same windows as MeetingTimeWindow (meeting_creation_tracker.dart).
  static const _windowNames = {
    'EARLY_MORNING': 'Early morning (5-8)', 'MORNING': 'Morning (8-12)',
    'MIDDAY': 'Midday (12-14)', 'AFTERNOON': 'Afternoon (14-18)',
    'EVENING': 'Evening (18-22)', 'NIGHT': 'Night (22-5)',
  };

  static String _dayLabel(String key) => _dayNames[key] ?? key;
  static String _windowLabel(String key) => _windowNames[key] ?? key;
  static String _dayWindowLabel(String key) {
    final split = key.indexOf('_');
    if (split < 0) return key;
    return '${_dayLabel(key.substring(0, split))} · ${_windowLabel(key.substring(split + 1))}';
  }
}

class _PeakRow extends StatelessWidget {
  final String label;
  final String value;
  const _PeakRow(this.label, this.value);

  @override
  Widget build(BuildContext context) => Padding(
        padding: const EdgeInsets.symmetric(vertical: 3),
        child: Row(
          children: [
            Expanded(
                child: Text(label,
                    style: const TextStyle(fontSize: 13, color: AppColors.textSecondary))),
            Text(value,
                style: const TextStyle(
                    fontSize: 13, fontWeight: FontWeight.w600, color: AppColors.text)),
          ],
        ),
      );
}
